export function localizeName(locale: Locale, map: Record<string, string>, name: string): string {
  if (locale === "en") return name;
  return map[name] ?? name;
}

export function localize<T extends string>(locale: Locale, en: T, bn: T): T {
  return locale === "bn" ? bn : en;
}
